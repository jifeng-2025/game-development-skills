#!/usr/bin/env python3
"""把皮肤 PNG 内联成 WebP data URL 常量（TS 模块）。preview / zip 里没有 dev 文件路由时用它。

  python inline_skin.py --skin-dir <PNG目录> --boxes boxes.json --out skin-images.ts [--used-in skin-hud.ts]

boxes.json：{"title/seal.png": [96, 96], ...}，值是这张图在 UI 舞台上的最大 CSS 显示框。
每张图缩到显示框的 2 倍（只缩小不放大；border-image 拉伸的图按较大一边保证 2 倍）。
--used-in：列出 boxes 里没有被该样式文件引用的图（文件路径或 --skin-* 变量名出现过就算引用）。不在 boxes 里的 PNG 也会列出来。
"""
import argparse
import base64
import io
import json
import os
import re

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--skin-dir', required=True)
    parser.add_argument('--boxes', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('--export', default='skinImages')
    parser.add_argument('--type-name', default='SkinFile')
    parser.add_argument('--quality', type=int, default=86)
    parser.add_argument('--alpha-quality', type=int, default=90)
    parser.add_argument('--used-in')
    args = parser.parse_args()
    boxes = json.load(open(args.boxes, encoding='utf-8'))
    lines = ['// Generated by inline_skin.py; do not edit by hand.', f'export const {args.export} = {{']
    rows = []
    for file, (bw, bh) in boxes.items():
        path = os.path.join(args.skin_dir, file)
        image = Image.open(path).convert('RGBA')
        w, h = image.size
        scale = min(1.0, max(2 * bw / w, 2 * bh / h))
        if scale < 1:
            image = image.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
        buffer = io.BytesIO()
        image.save(buffer, 'WEBP', quality=args.quality, alpha_quality=args.alpha_quality, method=6)
        data = buffer.getvalue()
        lines.append(f"  '{file}': 'data:image/webp;base64,{base64.b64encode(data).decode()}',")
        rows.append({'file': file, 'source': [w, h], 'out': list(image.size),
                     'pngBytes': os.path.getsize(path), 'webpBytes': len(data)})
    lines += ['} as const;', '', f'export type {args.type_name} = keyof typeof {args.export};', '']
    with open(args.out, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))
    on_disk = {os.path.relpath(os.path.join(d, f), args.skin_dir) for d, _, fs in os.walk(args.skin_dir) for f in fs if f.endswith('.png')}
    result = {'files': len(rows), 'pngBytes': sum(r['pngBytes'] for r in rows), 'webpBytes': sum(r['webpBytes'] for r in rows),
              'notInBoxes': sorted(on_disk - set(boxes)), 'rows': rows}
    if args.used_in:
        css = open(args.used_in, encoding='utf-8').read()
        var_name = lambda f: '--skin-' + re.sub(r'[^a-z0-9]+', '-', f[:-4] if f.endswith('.png') else f)
        result['unreferenced'] = [f for f in boxes if f not in css and var_name(f) not in css]
    print(json.dumps(result, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
