"""Inline images into a TypeScript module as WebP data URLs — the fix for `/@fs/<absolute path>` image URLs
that only resolve on the ForgeaX dev server (preview and the web-zip answer them with index.html).
Same mechanism as a hand-written `export const plate = 'data:image/...'` module; no loader, no bundler glob
(Pack cooking imports plugin modules in Node: import.meta.glob / `?url` imports fail there).

    python3 inline-images.py spec.json
    spec.json:
    {
      "sourceDir": "/abs/game/assets/art/ui/skin",
      "out": "/abs/game/assets/ui/skin-images.ts",
      "exportName": "skinImages",
      "quality": 86,
      "boxes": { "title/seal.png": [96, 96], "hud/hp-fill-red.png": [560, 28], ... },
      "crops": { "hexpick/icon-ink.png": {"source": "/abs/sheet.png", "box": [0,0,724,724], "size": [86,86], "circle": true} }
    }
boxes = largest CSS box (stage px) the image is drawn into; output is at most 2x that box on its larger
ratio axis, never upscaled (border-image stretches keep 2x along the stretched axis).
"""
import base64
import io
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw

if len(sys.argv) != 2:
    sys.exit(__doc__)
spec = json.load(open(sys.argv[1]))
src = Path(spec['sourceDir'])
quality = int(spec.get('quality', 86))
name = spec.get('exportName', 'images')


def circle(image):
    w, h = image.size
    inset = round(w * 0.045)
    mask = Image.new('L', image.size, 0)
    ImageDraw.Draw(mask).ellipse((inset, inset, w - inset, h - inset), fill=255)
    image.putalpha(mask)
    return image


jobs = [(key, src / key, None, tuple(box), False) for key, box in spec.get('boxes', {}).items()]
jobs += [(key, Path(c['source']), tuple(c['box']), tuple(c['size']), c.get('circle', False)) for key, c in spec.get('crops', {}).items()]
lines = [f'// Generated by inline-images.py from {src}; do not edit by hand.',
         f'export const {name} = {{']
total_in = total_out = 0
for key, path, crop, (bw, bh), round_cut in jobs:
    image = Image.open(path).convert('RGBA')
    if crop:
        image = image.crop(crop)
        if round_cut:
            image = circle(image)
    w, h = image.size
    scale = min(1.0, max(2 * bw / w, 2 * bh / h))
    if scale < 1:
        image = image.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
    buf = io.BytesIO()
    image.save(buf, 'WEBP', quality=quality, alpha_quality=90, method=6)
    data = buf.getvalue()
    total_in += path.stat().st_size if not crop else 0
    total_out += len(data)
    lines.append(f"  '{key}': 'data:image/webp;base64,{base64.b64encode(data).decode()}',")
    print(f'{key}: {w}x{h} -> {image.size[0]}x{image.size[1]}, {len(data)} B')
lines += ['} as const;', '', f'export type {name[0].upper()}{name[1:]}Key = keyof typeof {name};', '']
Path(spec['out']).write_text('\n'.join(lines))
print(json.dumps({'images': len(jobs), 'sourceBytes': total_in, 'webpBytes': total_out, 'out': spec['out']}))
